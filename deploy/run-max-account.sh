#!/bin/bash
# Аккаунт компании в MAX: приём входящих в переписку и отправка ответов менеджера.
# Использовать через pm2, см. docs/runbooks/max-account.md.
#
# Экземпляр должен быть ровно один. Вторая копия на том же токене — это второе устройство в
# их антифроде, а множественные входы с разных мест там ровно тот признак, за который
# аккаунт ограничивают.
set -e
# Проект требует Node >=24, а системный node на сервере старее (используется
# MAX-ботом) — берём Node 24 из nvm, не трогая системный node.
export NVM_DIR="$HOME/.nvm"
[ -s "$NVM_DIR/nvm.sh" ] && \. "$NVM_DIR/nvm.sh"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT/apps/max-account"
exec node --env-file="$ROOT/.env" --import tsx src/main.ts
