-- Касание может случиться вне кампании и без менеджера.
--
-- Лента касаний писалась только руками: менеджер открывал карточку в кампании и отмечал
-- звонок или сообщение. Отсюда две обязательности, которые с появлением переписки стали
-- неправдой.
--
-- **Кампания.** Человек, написавший боту, может не состоять ни в одной воронке. Требовать
-- строку участия означало бы либо не записывать его касание вовсе, либо заводить участие
-- в первой попавшейся кампании — то есть врать про то, откуда он взялся.
--
-- **Менеджер.** У входящего сообщения автор — сам человек, а не сотрудник. Приписать его
-- служебной учётной записи можно, и это выглядело бы в ленте как «Бот написал нам»: строка
-- есть, а смысл потерян. Пусто здесь честнее и читается однозначно — в панели такое касание
-- подписано «Человек».
--
-- Обязательным остаётся `contact_id`: касание без человека не касание. Именно поэтому
-- диалог без карточки в ленту не попадает — попасть ему некуда, и это видно в списке
-- неопознанных диалогов, а не теряется молча.

alter table public.outreach_activities
  alter column campaign_contact_id drop not null;

alter table public.outreach_activities
  alter column actor_admin_id drop not null;

comment on column public.outreach_activities.campaign_contact_id is
  'Участие в кампании, если касание случилось внутри неё. Пусто — человек написал сам.';
comment on column public.outreach_activities.actor_admin_id is
  'Кто из сотрудников сделал касание. Пусто — это сделал сам человек: он написал нам.';

-- Лента человека собирается по нему, а не по участию в кампании: касание вне кампании
-- иначе искалось бы перебором.
create index outreach_activities_contact_idx
  on public.outreach_activities (contact_id, occurred_at desc, id desc);
