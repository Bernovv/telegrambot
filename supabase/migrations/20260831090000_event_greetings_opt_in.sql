-- Приветствие по заявке включается у мероприятия явно, а не стоит включённым сразу.
--
-- Решение владельца от 26.10.2026: писать по заявкам только на мастер-классы Чурсина, а по
-- встрече 18 ноября — нет. Правило «включается галочкой» держит это само: новая встреча
-- никому не напишет, пока у неё не включили приветствие. Забытая галочка стоит одного
-- неотправленного «получили заявку», а включённое по умолчанию — волны первых сообщений
-- незнакомым людям с аккаунта, через который идёт вся переписка с клиентами.
--
-- Воркер и экран в панели уже считают «настроек нет» выключенным. Здесь выравнивается
-- значение по умолчанию у самой колонки, чтобы строка, заведённая без него, тоже значила
-- «выключено». Существующие строки не трогаем: в них галочку ставили руками.

alter table public.event_greetings
  alter column is_enabled set default false;

comment on column public.event_greetings.is_enabled is
  'Писать ли по заявкам на это мероприятие. По умолчанию нет — включают на экране «Приветствие».';
