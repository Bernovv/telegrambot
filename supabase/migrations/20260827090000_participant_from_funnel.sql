-- Участник, пришедший из воронки.
--
-- Решение владельца от 23.08.2026: доехал в воронке до этапа с исходом «выиграно» —
-- участник мероприятия заводится сам. Раньше список участников и воронка жили порознь, и
-- человека, оплатившего через менеджера, вносили в список руками.
--
-- **Почему не живой выборкой по этапу.** На строке участника висят явка, расселение, доли
-- команды и расходы. Живая выборка означала бы, что карточка, которую менеджер потянул не
-- туда, меняет списки расселения и деньги задним числом. Участник заводится один раз и
-- дальше живёт своей жизнью: перетаскивание карточки обратно его не трогает, а убирают его
-- руками и с причиной, как и любого другого.
--
-- Здесь нужен только новый источник: откуда участник взялся. Значений было четыре, и ни
-- одно не описывает воронку — `direct` означает «завели руками в панели», а разница между
-- «завели руками» и «доехал по воронке» видна в отчёте по источникам.

alter table public.event_participants
  drop constraint if exists event_participants_source_check;

alter table public.event_participants
  add constraint event_participants_source_check check (
    source in ('max', 'site', 'direct', 'funnel', 'other')
  );

comment on column public.event_participants.source is
  'Откуда участник: max | site | direct (руками) | funnel (доехал по воронке) | other';
