-- Прочитано или нет.
--
-- До сих пор у переписки не было ни одного признака прочтения: лента открывалась в карточке
-- человека, и «непрочитанного» в ней не существовало как понятия. Списку диалогов оно
-- нужно с первой минуты — без него список отвечает на вопрос «кто писал последним», но не
-- на вопрос «кому мы ещё не ответили», а работают именно со вторым.
--
-- **Почему по менеджеру, а не по диалогу.** В Telegram, MAX и WhatsApp с клиентом
-- разговаривает один аккаунт компании, но людей за ним несколько. Одна отметка на диалог
-- означала бы, что открывший его первым погасил кружок у всех остальных, — и второй
-- менеджер узнаёт о новом сообщении, только случайно зайдя в диалог. Отметка личная,
-- поэтому ключ составной.
--
-- **Почему время, а не счётчик.** Счётчик пришлось бы менять на каждое входящее, то есть
-- писать в эту таблицу столько же раз, сколько приходит сообщений, и держать его в
-- согласии с лентой. Время последнего прочтения меняется только когда человек открыл
-- диалог, а непрочитанное считается запросом по ленте, у которой для этого уже есть индекс
-- `(conversation_id, occurred_at desc, id desc)`.
--
-- **Почему нет строки «ни разу не открывал».** Её отсутствие и есть эта строка: нет записи
-- — не читал ничего, всё входящее непрочитано. Заводить строку каждому менеджеру на каждый
-- диалог заранее значило бы получить произведение двух таблиц там, где обычно нужна
-- пара десятков строк.

create table public.conversation_reads (
  conversation_id uuid not null references public.conversations(id),
  admin_id uuid not null references public.admin_accounts(id),
  -- Всё, что пришло не позже этого времени, менеджер видел. Сравнение строгое по «позже»:
  -- сообщение, пришедшее в ту же миллисекунду, что и открытие, человек всё-таки видел.
  last_read_at timestamptz not null,
  updated_at timestamptz not null default now(),
  primary key (conversation_id, admin_id)
);

-- «Сколько у меня непрочитанного» — вопрос про одного менеджера и все его диалоги сразу.
-- Первичный ключ на него не годится: он начинается с диалога.
create index conversation_reads_admin_idx
  on public.conversation_reads (admin_id, last_read_at desc);

comment on table public.conversation_reads is
  'До какого момента менеджер прочитал диалог. Строки нет — не читал ничего.';
comment on column public.conversation_reads.last_read_at is
  'Входящее позже этого времени считается непрочитанным для этого менеджера.';
