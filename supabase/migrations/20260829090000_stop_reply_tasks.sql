-- Задача «Ответить в переписке» больше не ставится сама.
--
-- Она появилась 23.08.2026, когда переписку было видно только внутри карточки человека: без
-- задачи входящее сообщение не всплывало нигде, и единственным способом о нём узнать было
-- открыть карточку и посмотреть. Задача была не про работу, а про уведомление.
--
-- Через два дня появился раздел «Переписки» со списком диалогов, счётчиком непрочитанного
-- в меню и отбором «непрочитанные». Тот же сигнал, только точнее: он гаснет, когда диалог
-- прочитали, а не когда кто-то нажал «выполнено». Задача с этого момента дублировала его и
-- добавляла в список дел строки, которые никто не заводил.
--
-- Решение владельца от 23.08.2026: убрать. Выключателем, а не удалением кода — он для этого
-- и был предусмотрен («пригодится в первый же день, когда окажется, что задач слишком
-- много»). Вернуть — одна строка `update`.

update public.conversation_task_settings
   set is_enabled = false,
       updated_at = now()
 where is_enabled;

-- Уже открытые снимаем: они говорят «ответь», а отвечать по ним предлагается в том же
-- месте, где теперь и так горит непрочитанное. Оставить их значит смешать в списке дел
-- настоящие задачи с уведомлениями, которых больше не будет.
--
-- Именно `cancelled`, а не `completed`: никто их не выполнял. И не удаление — по журналу
-- должно быть видно, что задачи были и почему исчезли.
--
-- Отбор узкий: только задачи по диалогу (`conversation_id`), то есть заведённые этой самой
-- автоматикой. Ручную задачу «позвонить», стоящую на человеке, не трогаем — за ней стоит
-- чьё-то решение.
update public.outreach_tasks
   set status = 'cancelled'
 where conversation_id is not null
   and status = 'open';
