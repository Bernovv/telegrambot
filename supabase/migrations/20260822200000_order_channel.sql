-- Канал заказа: где именно человек его оформил.
--
-- До сих пор это было известно, но нигде не записано: канал ровно один, и «где оформил»
-- совпадало с «где вообще есть бот». С появлением MAX совпадение кончается, и вопрос
-- становится денежным: билет после оплаты уходит в мессенджер, и без этой колонки очередь
-- доставки не знает, в какой именно.
--
-- Косвенные признаки для этого не годятся. Самый свежий опознаватель человека — это «где он
-- был последний раз», а не «где он купил»: купил в MAX, потом открыл Telegram — и билет
-- уехал бы не туда. Канал согласия с офертой ближе к правде, но акцепт бывает не у всякого
-- заказа. Поэтому отдельная колонка, заполняемая при создании заказа.
--
-- Значение по умолчанию правдиво: все существующие заказы оформлены в Telegram, другого
-- канала до сих пор не было.

alter table public.orders
  add column if not exists channel text not null default 'telegram';

alter table public.orders
  add constraint orders_channel_check check (
    channel in ('telegram', 'max', 'admin', 'web')
  );

comment on column public.orders.channel is
  'Где оформлен заказ. По нему очередь доставки выбирает, в какой мессенджер отправить билет.';

-- Отбор доставок по каналу: воркер спрашивает «чьи заказы», а не «все подряд».
create index if not exists orders_channel_idx
  on public.orders (channel, created_at desc);
