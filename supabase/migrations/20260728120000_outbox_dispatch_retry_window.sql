-- Расширяет окно повторов очереди доставки уведомлений.
--
-- Было: 5 попыток, задержка от 5 секунд с удвоением, потолок 300 секунд. В сумме это около
-- двух с половиной минут — то есть очередь переживала лишь мгновенную сетевую икоту. 27 июля
-- канал до Telegram (Cloudflare-прокси) был недоступен два часа, и задачи на выдачу билета и
-- уведомление администратору исчерпали повторы за первые минуты. Билет оплаченного заказа
-- пришлось возвращать в очередь руками, и заметили это только потому, что в тот момент
-- смотрели в логи.
--
-- Стало: 14 попыток с потолком задержки в 15 минут. Сумма задержек —
-- 10+20+40+80+160+320+640+900×7 ≈ 2 часа 45 минут. Это перекрывает сбой такой же
-- продолжительности, как случившийся, с запасом.
--
-- Само по себе это не отменяет надобности смотреть в очередь мёртвых писем
-- (outbox-dispatch-dead-letter): задача, не прошедшая и за три часа, по-прежнему туда попадёт.
-- Оттуда её достаёт `pnpm queue:dead-letter`.

update pgboss.queue
set retry_limit = 14,
    retry_delay = 10,
    retry_backoff = true,
    retry_delay_max = 900,
    updated_on = now()
where name = 'outbox-dispatch';

-- Уже созданные задачи держат лимит, скопированный из очереди в момент постановки, поэтому
-- поднимаем его и им — иначе новые правила заработают только для следующих покупок.
update pgboss.job
set retry_limit = 14,
    retry_delay = 10,
    retry_backoff = true,
    retry_delay_max = 900
where name = 'outbox-dispatch'
  and state in ('created', 'retry', 'active');
