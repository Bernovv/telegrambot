"use client";

import { useEffect, useState } from "react";

/**
 * Плашка «сделано», которая гаснет сама.
 *
 * Раньше она висела до следующего действия: перетащил карточку — «Контакт перемещён»,
 * поставил задачу — «Задача поставлена», и обе строки стояли над доской, пока не случится
 * что-нибудь ещё. На экране, где место считают пикселями, это дорого.
 *
 * Пять секунд — столько, чтобы прочитать короткую строку, и не столько, чтобы к ней
 * привыкнуть. Отсчёт начинается заново на каждое новое сообщение: пять действий подряд не
 * оставят пять плашек и не погасят последнюю раньше времени.
 *
 * Одно следствие, о котором стоит знать: **так же гаснут и сообщения об ошибке** — часть
 * экранов показывает их этой же плашкой. Человек в этот момент смотрит на экран, потому
 * что сам нажал кнопку, так что увидит; но если окажется, что нет, ошибки стоит развести с
 * успехами и оставлять до нажатия.
 */
export const NOTICE_TTL_MS = 5_000;

export function useNotice(): readonly [
  string | null,
  (text: string | null) => void
] {
  const [notice, setNotice] = useState<string | null>(null);

  useEffect(() => {
    if (notice === null) {
      return;
    }
    const timer = setTimeout(() => setNotice(null), NOTICE_TTL_MS);
    return () => clearTimeout(timer);
  }, [notice]);

  return [notice, setNotice] as const;
}
