/**
 * Что нужно знать, чтобы поднять аккаунт компании в MAX.
 *
 * Пакет намеренно не знает ни про `.env`, ни про базу: его дело — соединение и протокол.
 * Тот же клиент нужен скрипту входа, который никакой базы не открывает вовсе.
 *
 * Структурно совпадает с `MaxAccountConfig` из `@ticket-platform/config`: пакеты в этом
 * репозитории до конфигурации не дотягиваются, а расхождение поймает сборка приложения,
 * которое их связывает.
 */
export interface MaxAccountClientOptions {
  /**
   * Постоянный токен сессии. Его выдаёт вход по коду, и он же лежит в `.env`.
   *
   * В отличие от Telegram, где сессия — каталог TDLib на диске, здесь авторизация целиком
   * помещается в строку. Переезд сервера не требует нового кода из SMS; зато строка эта —
   * полный доступ к переписке, и место ей только в `.env`.
   *
   * `null` — клиент поднимется неавторизованным. Так работает скрипт входа.
   */
  readonly token: string | null;
  /**
   * Идентификатор устройства. Постоянный: меняющийся при каждом запуске выглядит для их
   * антифрода как вход с нового устройства — то самое поведение, за которое банят.
   */
  readonly deviceId: string;
  /** Как аккаунт подписан в списке устройств. Это видно владельцу номера в приложении. */
  readonly deviceName: string;
  /** Версия их веб-клиента, за которую мы себя выдаём. */
  readonly appVersion: string;
  readonly userAgent: string;
  readonly wsUrl: string;
  /** Сколько ждать ответа на вызов. */
  readonly requestTimeoutMs: number;
}

