/**
 * Что нужно знать, чтобы поднять аккаунт компании в WhatsApp.
 *
 * Пакет намеренно не знает ни про `.env`, ни про базу: его дело — соединение и протокол.
 * Тот же клиент нужен скрипту входа, который никакой базы не открывает вовсе.
 *
 * Структурно совпадает с `WhatsAppAccountConfig` из `@ticket-platform/config`: пакеты в этом
 * репозитории до конфигурации не дотягиваются, а расхождение поймает сборка приложения,
 * которое их связывает.
 */
export interface WhatsAppAccountClientOptions {
  /**
   * Каталог сессии.
   *
   * Главное отличие от MAX, где вся авторизация помещалась в строку `MAX_ACCOUNT_TOKEN`.
   * Здесь сессия — это учётные данные плюс сигнальные ключи, которые меняются после каждого
   * сообщения; строкой в `.env` это не положить. Каталог живёт на диске с правами `700`, и
   * **его надо резервировать**: потеря означает новую привязку по коду, а код вводят на
   * телефоне, до которого в этот момент ещё надо дотянуться.
   */
  readonly sessionDir: string;
  /**
   * Номер аккаунта: международный вид, только цифры, без плюса. Сверяется после входа —
   * перепутанный номер это не опечатка в конфиге, а разговор клиента с посторонним.
   */
  readonly phone: string;
  /** Как аккаунт подписан в списке устройств. Это видно владельцу номера в приложении. */
  readonly deviceName: string;
  /**
   * Прокси, обязательный на продакшне.
   *
   * WhatsApp с российского сервера напрямую недоступен: домены исключены из национальной
   * системы доменных имён. Ходим через ту же амстердамскую машину, что и Telegram-аккаунт, —
   * там обычный SOCKS5, ему всё равно, чей трафик перекладывать.
   *
   * Своей переменной, а не общей с Telegram: значение одинаковое, но одна правка не должна
   * гасить два канала сразу.
   */
  readonly proxyUrl: string | null;
  /** Сколько ждать ответа на вызов. */
  readonly requestTimeoutMs: number;
}

export const WHATSAPP_ACCOUNT_DEFAULTS = {
  deviceName: "Бизнес-Прорыв CRM",
  requestTimeoutMs: 60_000
} as const;
